/// Database of file magic bytes (file signatures) mapped to file extensions.
///
/// Entries are sorted by signature length in descending order so that
/// longer (more specific) signatures are matched before shorter ones.

List<int> _hex(String s) =>
    s.split(' ').where((b) => b.isNotEmpty).map((b) => int.parse(b, radix: 16)).toList();

class MagicEntry {
  final List<int> signature;
  final String ext;
  MagicEntry(this.signature, this.ext);
}

